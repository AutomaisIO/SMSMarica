    private static ProcedimentoSigtap Item(
        string id,
        string codigoCru,
        string nome,
        string grupo,
        string subgrupo,
        string forma) => new()
    {
        Id = Guid.Parse(id),
        Codigo = FormatarCodigo(codigoCru),
        Nome = nome,
        Grupo = grupo,
        Subgrupo = subgrupo,
        Forma = forma,
        Descricao = nome,
        Ativo = true,
        CompetenciaInicio = CompetenciaInicio,
        CompetenciaFim = null,
    };

    /// <summary>"0204030188" → "02.04.03.018-8"</summary>
    private static string FormatarCodigo(string cru) =>
        cru.Length == 10
            ? $"{cru[..2]}.{cru.Substring(2, 2)}.{cru.Substring(4, 2)}.{cru.Substring(6, 3)}-{cru[9]}"
            : cru;
}
